/* Возвращает компонент с показаниями, пересчитанными под вариант i */
MC.variant = function (comp, i) {
  var list = MC.variants[comp.id];
  if (!list || !list.length) return comp;
  var v = list[i % list.length];
  var s = v.s || {};
  function scaled(key, val) {
    if (typeof val !== 'number') return val;
    var k = key.indexOf('on|') === 0 ? key.slice(3) : key;
    var mode = k.split(':')[0];
    var f = s[k];
    if (f === undefined && k.indexOf('|') > 0) { var p = k.split(':'); var rev = p[0] + ':' + p[1].split('|').reverse().join('|'); f = s[rev]; }
    if (f === undefined) f = s[mode];
    return f === undefined ? val : val * f;
  }
  var c = Object.assign({}, comp);
  c.variantIndex = i % list.length;
  c.variantCount = list.length;
  c.variantLabel = v.label;
  c.marking = v.m || null;
  c.base = comp;
  c.states = comp.states.map(function (st) {
    var r = {};
    Object.keys(st.r).forEach(function (k) { r[k] = scaled(k, st.r[k]); });
    return Object.assign({}, st, { r: r, note: st.ok ? v.label : st.note });
  });
  return c;
};
